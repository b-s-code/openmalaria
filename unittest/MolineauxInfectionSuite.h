    static void readVector(std::vector<double>& vec, const char* file){
        ifstream istr(file);
        ETS_ASSERT( istr.is_open() );
        double val;
        while( istr >> val ){
            vec.push_back( val );
        }
        ETS_ASSERT( istr.eof() );
    }
    
    void testDensities(){
        UnittestUtil::molineauxWhmSetup( "pairwise", false );
        
        // read densities: these were simply generated by this code, so the
        // only useful thing this test does is spot changes in output!
        vector<double> dens;
        readVector(dens,"MolineauxCirDens.txt");
//         ofstream out("MolineauxCirDens.txt");
//         out << setprecision(8);
        
        // pkpdID (value) isn't important since we're not using drug model here:
        MolineauxInfection* infection = new MolineauxInfection (m_rng, 0xFFFFFFFF, InfectionOrigin::Indigenous);
        bool extinct = false;
        size_t day=0;
        SimTime now = Sim::ts0();
        do{
            extinct = infection->update(m_rng, 1.0 /*no external immunity*/, now, 71.43 /*adult body mass in kg to get 5l blood volume*/);
            SimTime age = now - infection->m_startDate - infection->s_latentP;
            if( age >= Sim::zero() ){
                ETS_ASSERT_LESS_THAN( day, dens.size() );
                TS_ASSERT_APPROX( infection->getDensity(), dens[day] );
//                 out << infection->getDensity() << endl;
                day += 1;
            }
            now = now + Sim::oneDay();
        }while(!extinct);
        TS_ASSERT_EQUALS( day, dens.size() );
        delete infection;
    }
    
